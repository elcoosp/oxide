//! The §V2-F01 island boot planner — the pure compiler-side emission
//! the build's `__boot__` entry and the tooling's `.oxide/islands.json`
//! come from. The inference order lives in the config crate
//! (`island_framework`); the CLI resolves each registry entry (reading
//! the file's first line for the pragma) and hands the resolved set
//! here, so this module never touches the filesystem (the F04 ruling:
//! config → engine conversion is wiring, not a dependency).
//!
//! Two shapes:
//!
//! - **single-framework** (the legacy contract, byte-preserving): the
//!   page adapter's static import, the static island imports + the
//!   `modules` map, `installBootRuntime()`,
//!   `window.__oxideRegisterAdapter(clientAdapter, ...)`, the §8.4
//!   loading map and the `bootWithRouter` tail. Existing
//!   single-framework apps and the conformance suite see no drift.
//! - **mixed** (the registry shape): one lazy adapter import per
//!   framework present (deduplicated) and an `islands` map carrying
//!   `{ fw, load }` per entry — `installBootRuntime({ adapters,
//!   islands })` — with the page adapter's static import, the §8.4
//!   loading map and the `bootWithRouter` tail unchanged (the router
//!   contract keeps its sequencing).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// One resolved island: the source path (relative to the project
/// root) and the framework the inference picked.
#[derive(Debug, Clone, PartialEq)]
pub struct ResolvedIsland {
    /// The source path, relative to the project root.
    pub src: String,
    /// The framework (`react | vue | svelte | solid`).
    pub framework: String,
}

/// The planned boot: the adapters the islands need and the resolved
/// entries, ordered by name.
#[derive(Debug, Clone, PartialEq)]
pub struct IslandBootPlan {
    /// The page framework the entry statically imports.
    pub project_framework: String,
    /// The lazy adapter import per framework present (sorted;
    /// deduplicated — several islands share one adapter).
    pub adapters: BTreeMap<String, String>,
    /// The resolved islands (sorted by name).
    pub islands: BTreeMap<String, ResolvedIsland>,
    /// More than one framework is present: the registry shape.
    pub mixed: bool,
}

/// Plan the boot from the resolved islands. The adapter import for a
/// framework is the package root (`@oxide-fw/<framework>`, the
/// `clientAdapter` export the legacy entry already uses — the
/// per-framework vendor chunking is the rolldown `advancedChunks`
/// half, documented in `docs/deviations.md`).
#[must_use]
pub fn plan_island_boot(
    project_framework: &str,
    islands: &BTreeMap<String, ResolvedIsland>,
) -> IslandBootPlan {
    let mut adapters: BTreeMap<String, String> = BTreeMap::new();
    for island in islands.values() {
        adapters
            .entry(island.framework.clone())
            .or_insert_with(|| format!("@oxide-fw/{}", island.framework));
    }
    let mixed = adapters.len() > 1;
    IslandBootPlan {
        project_framework: project_framework.to_string(),
        adapters,
        islands: islands.clone(),
        mixed,
    }
}

/// One tooling payload record (`.oxide/islands.json`).
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
struct IslandsJsonEntry<'a> {
    /// The island's source path (the configured one).
    chunk: &'a str,
    /// The framework the inference picked.
    framework: &'a str,
}

impl IslandBootPlan {
    /// The `.oxide/islands.json` payload (`{ Name: { chunk, framework } }`,
    /// sorted, compact) the `oxide why`/F17 overlays read.
    #[must_use]
    pub fn islands_json(&self) -> String {
        let map: BTreeMap<&String, IslandsJsonEntry<'_>> = self
            .islands
            .iter()
            .map(|(name, island)| {
                (
                    name,
                    IslandsJsonEntry {
                        chunk: &island.src,
                        framework: &island.framework,
                    },
                )
            })
            .collect();
        serde_json::to_string(&map).unwrap_or_else(|_| "{}".to_string())
    }

    /// The generated `__boot__` entry source.
    #[must_use]
    pub fn boot_entry_source(
        &self,
        root: &Path,
        loading: &BTreeMap<String, std::path::PathBuf>,
        pwa: bool,
    ) -> String {
        let mut out = String::new();
        out.push_str("// Generated by oxide-fw-cli -- island boot entry. Do not edit.\n");
        if self.mixed {
            out.push_str("// The mixed registry hydrates each island through its own\n");
            out.push_str("// framework's adapter; the page adapter stays static for the\n");
            out.push_str("// §8.4 boot sequencing.\n");
        } else {
            out.push_str("// Static imports resolve before any statement runs, so `boot()`\n");
            out.push_str("// can see both the adapter and the boot runtime's registration hook.\n");
        }
        // `clientAdapter` is the browser-side adapter each framework package
        // exports. For React it wires `react-dom/client` hydration (so `useState`
        // survives); for the others it aliases the neutral-IR adapter today.
        // The named `adapter` export stays the neutral-IR form for tests and the
        // §22 conformance suite, so its `hydrateIsland` continues to work against
        // the fake DOM.
        let _ = writeln!(
            out,
            "import {{ clientAdapter }} from '@oxide-fw/{}';",
            self.project_framework
        );
        out.push_str(
            "import { bootWithRouter, installBootRuntime } from '@oxide-fw/core/client/boot';\n",
        );

        if self.mixed {
            out.push_str("\nconst adapters = {\n");
            for (fw, specifier) in &self.adapters {
                let _ = writeln!(out, "  {fw}: () => import('{specifier}'),");
            }
            out.push_str("};\n\n");
            out.push_str("const islands = {\n");
            for (name, island) in &self.islands {
                let abs = root.join(&island.src);
                let _ = writeln!(
                    out,
                    "  {name:?}: {{ fw: '{}', load: () => import({:?}) }},",
                    island.framework,
                    abs.to_string_lossy()
                );
            }
            out.push_str("};\n");
            out.push_str("installBootRuntime({ adapters, islands });\n");
        } else {
            let mut idents: Vec<(String, String)> = Vec::new();
            for (name, island) in &self.islands {
                let abs = root.join(&island.src);
                let ident = format!(
                    "__island_{}",
                    name.chars()
                        .map(|c| if c.is_ascii_alphanumeric() || c == '_' {
                            c
                        } else {
                            '_'
                        })
                        .collect::<String>()
                );
                let _ = writeln!(out, "import {ident} from {:?};", abs.to_string_lossy());
                idents.push((name.clone(), ident));
            }
            out.push_str("\nconst modules = {\n");
            for (name, ident) in &idents {
                let _ = writeln!(out, "  {name:?}: {ident},");
            }
            out.push_str("};\n\n");
            out.push_str("installBootRuntime();\n");
        }

        // §8.4 loading boundaries: a `route directory → loading component`
        // map. Each route's directory (e.g. `routes/`, `routes/blog/`) is
        // emitted as a URL path key so the client router can match the URL it
        // is navigating to. The boot entry imports each loading module
        // statically; a project without loading.tsx emits `{}`.
        //
        // KEY CONTRACT (client matcher, §8.4): a key is an ABSOLUTE PATH whose
        // segments may be `[name]` tokens (the literal bracket dir token the
        // scanner keeps in route ids, e.g. `routes/blog/[slug]/loading` →
        // `/blog/[slug]`). A `[name]` key segment matches exactly ONE
        // non-empty URL segment; the longest key (most segments) wins; the
        // root key is `/`. No trailing slash on non-root keys — the matcher
        // compares segment-by-segment, so `/blog/[slug]` matches `/blog/x`
        // (the old literal-prefix key `/blog/[slug]/` matched nothing).
        if loading.is_empty() {
            out.push_str("\nconst __loading_map = {};\n\n");
        } else {
            push_loading_map(&mut out, root, loading);
        }

        if !self.mixed {
            out.push_str(
                "window.__oxideRegisterAdapter(clientAdapter, async (chunk) => {\n  \
                 return modules[chunk] ?? (await import(chunk));\n});\n",
            );
        }
        // §8.4: hydrate the SSR root, scan islands, THEN attach the client router.
        // `bootWithRouter` is the sequenced form: it calls `adapter.hydrate(root,
        // input)` (which sets the adapter module's `active` handle that `update()`
        // later needs) BEFORE installing the router's click listener. Attaching
        // `createRouter` without a preceding `adapter.hydrate` was the pre-fix
        // bug — a same-origin link click changed the URL and the DOM did not
        // re-render (worse than no router, because the pre-fix page still worked
        // via full page load).
        //
        // The client manifest is still not consumed (SPA nav fetches `/__data`;
        // manifest-driven chunk preloading is a documented gap, not silently
        // stubbed). A hydrate failure leaves the SSR markup untouched and skips
        // router attachment so anchors fall back to full-page navigation.
        // §6.4: fetch the client manifest at boot so the router can preload a
        // route's chunks in parallel with the /__data fetch. The fetch is
        // best-effort — a missing manifest (dev server, static export without it)
        // leaves `manifest` undefined and the router silently skips preloading.
        out.push_str(
            "fetch('/client/client.manifest.json')\n  \
             .then((r) => (r.ok ? r.json() : undefined))\n  \
             .then((manifest) => bootWithRouter(clientAdapter, { loading: __loading_map, manifest }))\n  \
             .catch(() => bootWithRouter(clientAdapter, { loading: __loading_map }));\n",
        );
        // §16.6 / §20: report Core Web Vitals to `/_oxide/vitals`. Guarded and
        // no-op outside the browser; the boot entry only runs in one.
        out.push_str(
            "import { reportWebVitals } from '@oxide-fw/core/client';\nreportWebVitals();\n",
        );
        // §16.6 / SPEC-21: auto-register the service worker when the project
        // configured a PWA manifest. `emit_pwa_worker` wrote `/pwa-register.js`;
        // loading it from the boot entry is what the spec's "auto-registration"
        // means (previously the script was emitted but never loaded).
        if pwa {
            // §16.6: register the service worker at runtime, not via a
            // static `import('/pwa-register.js')`. The latter is resolved by
            // rolldown at bundle time, but `/pwa-register.js` is written by
            // `emit_pwa_worker` AFTER bundling — so a clean build fails with
            // "Could not resolve /pwa-register.js". A runtime `<script>`
            // injection sidesteps the bundler entirely and matches what a
            // manual PWA registration does anyway.
            out.push_str(
                "if (typeof navigator !== 'undefined' && 'serviceWorker' in navigator && !globalThis.__oxidePwaRegistered) {\n  \
                 globalThis.__oxidePwaRegistered = true;\n  \
                 var __oxidePwa = document.createElement('script');\n  \
                 __oxidePwa.src = '/pwa-register.js';\n  \
                 __oxidePwa.async = true;\n  \
                 document.head.appendChild(__oxidePwa);\n}\n",
            );
        }
        out
    }
}

/// The §8.4 loading-map emission: a `route directory → loading
/// component` map keyed by ABSOLUTE PATH whose segments may be `[name]`
/// tokens (the matcher compares segment-by-segment; the longest key
/// wins; the root key is `/`). Each loading module rides a static
/// import and a `__loading_<ident>` binding.
fn push_loading_map(out: &mut String, root: &Path, loading: &BTreeMap<String, std::path::PathBuf>) {
    let mut loading_idents: Vec<(String, String)> = Vec::new();
    for (route_id, src) in loading {
        // `routes/blog/[slug]/loading` → `/blog/[slug]` (bracket tokens
        // preserved verbatim). `routes/loading` → `/`.
        let dir = route_id
            .strip_suffix("/loading")
            .unwrap_or(route_id)
            .strip_prefix("routes")
            .unwrap_or(route_id)
            .to_string();
        let url_key = if dir.is_empty() { "/".to_string() } else { dir };
        let abs = root.join(src);
        let ident = format!(
            "__loading_{}",
            route_id
                .chars()
                .map(|c| if c.is_ascii_alphanumeric() || c == '_' {
                    c
                } else {
                    '_'
                })
                .collect::<String>()
        );
        let _ = writeln!(out, "import {ident} from {:?};", abs.to_string_lossy());
        loading_idents.push((url_key, ident));
    }
    let _ = writeln!(out, "\nconst __loading_map = {{");
    for (url_prefix, ident) in &loading_idents {
        let _ = writeln!(out, "  {url_prefix:?}: {ident},");
    }
    out.push_str("};\n\n");
}
