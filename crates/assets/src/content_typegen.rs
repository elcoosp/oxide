//! §16-C: `content.d.ts` typegen.
//!
//! Emits a typed shape for every content collection: an `Entry` interface
//! per collection (slug + every declared field), a `Collection` map, and a
//! `content` object with a query helper per collection. A user writes
//!
//! ```ts
//! import { content } from '../.oxide/types/content'
//! const posts = content.blog.all()        // BlogEntry[]
//! const one   = content.blog.bySlug('x')  // BlogEntry | undefined
//! ```
//!
//! Field types come from the collection's schema. `NativeSchema` carries
//! required + optional fields with a `FieldType`; `Unchecked` and `External`
//! schemas fall back to `Record<string, unknown>` for the frontmatter, with
//! the universal `slug` still typed `string`.

use crate::content_collection::{Collection, FieldType, NativeSchema, SchemaKind};
use oxide_diagnostics::Result;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// One collection's schema, as the typegen needs it. `schema` is `None` for
/// an `Unchecked` / `External` collection — those get a loose frontmatter
/// type.
pub struct TypedCollection<'a> {
    pub collection: &'a Collection,
    pub schema: Option<&'a NativeSchema>,
}

/// Emit `.oxide/types/content.d.ts`. `collections` may be empty — the file
/// still names the exported `content` object with an empty map, so a user
/// import never fails to resolve.
pub fn write_content_dts(
    collections: &[TypedCollection<'_>],
    out_path: &std::path::Path,
) -> Result<()> {
    let mut out = String::new();
    out.push_str("// Generated by oxide assets content typegen (spec §16-C). DO NOT EDIT.\n\n");

    // One entry interface per collection.
    for c in collections {
        let iface = interface_name(&c.collection.name);
        let _ = writeln!(out, "export interface {iface} {{");
        out.push_str("  /** URL-safe id of the entry. */\n");
        out.push_str("  readonly slug: string;\n");
        match c.schema {
            Some(schema) => {
                for (field, ty) in &schema.required {
                    let _ = writeln!(out, "  readonly {field}: {};", ts_type(ty));
                }
                for (field, ty) in &schema.optional {
                    let _ = writeln!(out, "  readonly {field}?: {};", ts_type(ty));
                }
            }
            None => {
                out.push_str(
                    "  /** Unchecked/External schema — frontmatter shape is not typed. */\n",
                );
                out.push_str("  readonly [field: string]: unknown;\n");
            }
        }
        out.push_str("}\n\n");
    }

    // The union of every entry type, and the per-collection query surface.
    if collections.is_empty() {
        out.push_str("export interface CollectionMap {\n}\n\n");
        out.push_str("export interface ContentApi {\n}\n\n");
        out.push_str("export const content: ContentApi\n");
    } else {
        out.push_str("export interface CollectionMap {\n");
        for c in collections {
            let _ = writeln!(
                out,
                "  {}: {};",
                ts_property_key(&c.collection.name),
                interface_name(&c.collection.name),
            );
        }
        out.push_str("}\n\n");

        out.push_str("export interface ContentApi {\n");
        for c in collections {
            let iface = interface_name(&c.collection.name);
            let _ = writeln!(
                out,
                "  /** Every entry in the `{}` collection. */",
                c.collection.name
            );
            let _ = writeln!(
                out,
                "  readonly {}: {{",
                ts_property_key(&c.collection.name)
            );
            let _ = writeln!(out, "    all(): readonly {iface}[];");
            let _ = writeln!(out, "    bySlug(slug: string): {iface} | undefined;");
            out.push_str("  };\n");
        }
        out.push_str("}\n\n");
        out.push_str("export const content: ContentApi\n");
    }

    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| {
            crate::err(
                "CONTENT-TYPEGEN",
                format!("mkdir {}: {e}", parent.display()),
            )
        })?;
    }
    std::fs::write(out_path, out).map_err(|e| {
        crate::err(
            "CONTENT-TYPEGEN",
            format!("write {}: {e}", out_path.display()),
        )
    })?;
    Ok(())
}

/// `blog` → `BlogEntry`; `changelog-v2` → `ChangelogV2Entry`.
fn interface_name(collection: &str) -> String {
    let mut s = String::with_capacity(collection.len() + 5);
    let mut upper = true;
    for c in collection.chars() {
        if c.is_alphanumeric() {
            s.push(if upper { c.to_ascii_uppercase() } else { c });
            upper = false;
        } else {
            upper = true;
        }
    }
    s.push_str("Entry");
    s
}

/// `blog` is a bare identifier; anything with a `-` needs quoting.
fn ts_property_key(collection: &str) -> String {
    if collection
        .chars()
        .all(|c| c.is_alphanumeric() || c == '_' || c == '$')
        && !collection
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_digit())
    {
        collection.to_string()
    } else {
        format!("\"{}\"", collection.replace('"', "\\\""))
    }
}

fn ts_type(ty: &FieldType) -> String {
    match ty {
        FieldType::String => "string".to_string(),
        FieldType::Number => "number".to_string(),
        FieldType::Bool => "boolean".to_string(),
        FieldType::Array(inner) => format!("readonly {}[]", ts_type(inner)),
        FieldType::Enum(variants) => variants
            .iter()
            .map(|v| format!("\"{}\"", v.replace('"', "\\\"")))
            .collect::<Vec<_>>()
            .join(" | "),
    }
}

/// Infer a `NativeSchema` from the entries actually on disk.
///
/// The config carries no schema field yet (`CollectionDef` has name/dir/
/// indexedFields), so `scan_collection` runs `Unchecked` — every frontmatter
/// value is `serde_json::Value`. That would give `content.d.ts` a loose
/// `Record<string, unknown>` and no per-field typing, which is not worth
/// generating.
///
/// Inferring from the observed union is: a field present in EVERY entry is
/// `required`; present in some is `optional`. The type is the union of the
/// value shapes seen, widened to one `FieldType` (a field that is a number in
/// one entry and a string in another is `String | Number`, which `FieldType`
/// cannot express — it widens to `String`, the safe supertype for display).
/// An explicit `NativeSchema` in config, when that field exists, overrides
/// this.
pub fn infer_schema(collection: &Collection) -> NativeSchema {
    use serde_json::Value;
    let total = collection.entries.len();
    // field → (observed type, count seen)
    let mut seen: BTreeMap<String, (FieldType, usize)> = BTreeMap::new();
    for entry in &collection.entries {
        for (field, value) in &entry.frontmatter {
            let ty = field_type_of(value);
            let slot = seen.entry(field.clone()).or_insert((ty.clone(), 0));
            slot.0 = widen(&slot.0, &ty);
            slot.1 += 1;
        }
    }
    let mut required = BTreeMap::new();
    let mut optional = BTreeMap::new();
    for (field, (ty, count)) in seen {
        if count == total && total > 0 {
            required.insert(field, ty);
        } else {
            optional.insert(field, ty);
        }
    }
    NativeSchema { required, optional }
}

fn field_type_of(v: &serde_json::Value) -> FieldType {
    match v {
        serde_json::Value::Bool(_) => FieldType::Bool,
        serde_json::Value::Number(_) => FieldType::Number,
        serde_json::Value::String(_) => FieldType::String,
        serde_json::Value::Array(a) => {
            // Array elements' type; the wrapper is what makes the emitted
            // TypeScript `readonly <elem>[]`. An empty array widens to
            // `readonly string[]` — the safe display type.
            FieldType::Array(Box::new(
                a.first().map(field_type_of).unwrap_or(FieldType::String),
            ))
        }
        // Object, Null, or anything else — String is the safe display type.
        _ => FieldType::String,
    }
}

/// Merge two observed types. Same → same; `T` + `String` → `String` (the
/// supertype a template interpolation accepts); `Number` + `Bool` → `String`
/// (no narrower common type in `FieldType`).
fn widen(a: &FieldType, b: &FieldType) -> FieldType {
    if a == b {
        return a.clone();
    }
    FieldType::String
}

/// Build the `(name → schema)` lookup `cmd_build` needs. A collection whose
/// config carries a `NativeSchema` gets a typed shape; `Unchecked` /
/// `External` get `None`.
pub fn schemas_from(
    defs: &[crate::content_collection::CollectionConfig],
) -> BTreeMap<String, Option<NativeSchema>> {
    let mut out = BTreeMap::new();
    for d in defs {
        let schema = match &d.schema {
            SchemaKind::Native(s) => Some(s.clone()),
            SchemaKind::Unchecked | SchemaKind::External { .. } => None,
        };
        out.insert(d.name.clone(), schema);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_typed_entry_and_query_surface() {
        let collection = Collection {
            name: "blog".to_string(),
            dir: std::path::PathBuf::from("content/blog"),
            entries: vec![],
        };
        let mut required = BTreeMap::new();
        required.insert("title".to_string(), FieldType::String);
        required.insert("draft".to_string(), FieldType::Bool);
        let mut optional = BTreeMap::new();
        optional.insert(
            "tags".to_string(),
            FieldType::Array(Box::new(FieldType::String)),
        );
        let schema = NativeSchema { required, optional };
        let tc = TypedCollection {
            collection: &collection,
            schema: Some(&schema),
        };

        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("content.d.ts");
        write_content_dts(&[tc], &out).unwrap();
        let body = std::fs::read_to_string(&out).unwrap();

        assert!(body.contains("export interface BlogEntry {"), "{body}");
        assert!(body.contains("readonly slug: string;"), "{body}");
        assert!(body.contains("readonly title: string;"), "{body}");
        assert!(body.contains("readonly draft: boolean;"), "{body}");
        assert!(
            body.contains("readonly tags?: readonly string[];"),
            "{body}"
        );
        assert!(body.contains("blog: BlogEntry;"), "{body}");
        assert!(body.contains("all(): readonly BlogEntry[];"), "{body}");
        assert!(
            body.contains("bySlug(slug: string): BlogEntry | undefined;"),
            "{body}"
        );
    }

    #[test]
    fn infer_schema_from_entries() {
        use std::collections::BTreeMap;
        let mk = |pairs: &[(&str, serde_json::Value)]| {
            let mut fm = BTreeMap::new();
            for (k, v) in pairs {
                fm.insert((*k).to_string(), v.clone());
            }
            crate::content_collection::CollectionEntry {
                slug: "x".to_string(),
                path: std::path::PathBuf::from("x.md"),
                frontmatter: fm,
                body_markdown: String::new(),
                is_mdx: false,
            }
        };
        let collection = Collection {
            name: "blog".to_string(),
            dir: std::path::PathBuf::from("content/blog"),
            entries: vec![
                mk(&[
                    ("title", serde_json::json!("a")),
                    ("draft", serde_json::json!(false)),
                ]),
                mk(&[
                    ("title", serde_json::json!("b")),
                    ("tags", serde_json::json!(["x", "y"])),
                ]),
            ],
        };
        let schema = infer_schema(&collection);
        assert_eq!(
            schema.required.get("title"),
            Some(&FieldType::String),
            "title required"
        );
        assert_eq!(
            schema.optional.get("draft"),
            Some(&FieldType::Bool),
            "draft optional"
        );
        assert!(schema.optional.contains_key("tags"), "tags optional");
        assert!(
            !schema.required.contains_key("draft"),
            "draft is not required"
        );
    }

    #[test]
    fn empty_collections_still_emit_a_usable_file() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("content.d.ts");
        write_content_dts(&[], &out).unwrap();
        let body = std::fs::read_to_string(&out).unwrap();
        assert!(body.contains("export interface CollectionMap"), "{body}");
        assert!(body.contains("export const content: ContentApi"), "{body}");
    }

    #[test]
    fn unchecked_collection_gets_loose_frontmatter() {
        let collection = Collection {
            name: "changelog".to_string(),
            dir: std::path::PathBuf::from("content/changelog"),
            entries: vec![],
        };
        let tc = TypedCollection {
            collection: &collection,
            schema: None,
        };
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("content.d.ts");
        write_content_dts(&[tc], &out).unwrap();
        let body = std::fs::read_to_string(&out).unwrap();
        assert!(
            body.contains("readonly [field: string]: unknown;"),
            "{body}"
        );
    }
}
