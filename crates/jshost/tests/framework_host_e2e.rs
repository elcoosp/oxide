//! End-to-end test: real config file → real FrameworkAdapter → real SSR HTML
//! (spec §6.3, §7). Runtime proof that FrameworkHost works.
//!
//! Requires:
//!   - Node on PATH (>=22.18 for native TS stripping; the config imports the
//!     adapter's `.ts` modules from packages/react/src/)
//!   - pnpm-installed workspace node_modules (react, react-dom present)
//!
//! `#[ignore]` by default because it spawns a Node process and touches the
//! filesystem. Run explicitly:
//!     cargo test -p oxide-jshost --test framework_host_e2e -- --ignored
//!
//! ## Test isolation
//!
//! Each test that writes a config uses a UNIQUE FILENAME at the base dir
//! `packages/react/.tmp-e2e/oxide-<nonce>.config.mjs`. The base dir is
//! deliberately inside `packages/react/` so the config's `from 'react'`
//! import resolves via the workspace node_modules, and its
//! `from '../src/real-adapter.ts'` relative import resolves to
//! `packages/react/src/real-adapter.ts`. Both paths are correct only when
//! the config file is a direct child of `.tmp-e2e/` — hence the unique
//! filename (not a unique subdir). Tests that only exercise missing-config
//! paths never write anything.

use oxide_jshost::{FrameworkHost, JsHost, NodeHost, PoolConfig};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent().expect("crates/")
        .parent().expect("workspace root")
        .to_path_buf()
}

fn e2e_base() -> PathBuf {
    workspace_root().join("packages/react/.tmp-e2e")
}

fn unique_nonce() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    format!("{pid}-{nanos}", pid = std::process::id())
}

/// A unique config file path under `.tmp-e2e/`; removed on drop.
struct E2eConfigFile(PathBuf);

impl E2eConfigFile {
    fn new() -> Self {
        let dir = e2e_base();
        fs::create_dir_all(&dir).expect("mkdir .tmp-e2e");
        let name = format!("oxide-{}.config.mjs", unique_nonce());
        Self(dir.join(name))
    }
    fn path(&self) -> &Path { &self.0 }
    fn path_str(&self) -> String { self.0.to_string_lossy().to_string() }
}

impl Drop for E2eConfigFile {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.0);
    }
}

const CONFIG_SOURCE: &str = r#"// Auto-generated by crates/jshost/tests/framework_host_e2e.rs
// Real React component + real react-dom/server dispatch through the
// FrameworkAdapter contract (spec §7). Removed by the test.

import { createRealAdapter } from '../src/real-adapter.ts'
import { createElement } from 'react'

const Home = (props) =>
  createElement('h1', { className: 'greeting' },
    'Hello from ' + String((props && props.data && props.data.name) || 'React'))

export default {
  framework: createRealAdapter({
    ssr: 'real',
    componentFor: (route) => (route === 'routes/index' ? Home : undefined),
  }),
}
"#;

#[tokio::test]
#[ignore]
async fn end_to_end_load_and_render_real_react_config() {
    let file = E2eConfigFile::new();
    fs::write(file.path(), CONFIG_SOURCE).expect("write config");
    let config_str = file.path_str();

    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    let fw = FrameworkHost::new(pool);

    // (1) load_config: descriptor round-trips through the real adapter.
    let descriptor = fw
        .load_config(&config_str)
        .await
        .expect("load_config");
    assert_eq!(descriptor.name, "react", "adapter name from the config");
    assert_eq!(descriptor.extensions, vec![".tsx".to_string()]);
    assert_eq!(descriptor.capabilities["islands"], true);

    // (2) render: real react-dom/server HTML comes back through the host.
    let input = serde_json::json!({
        "route": "routes/index",
        "url": "/",
        "params": {},
        "data": { "name": "E2E" },
        "head": {
            "title": "E2E",
            "meta": [{ "name": "x-e2e", "content": "yes" }],
            "link": [], "style": [], "script": []
        },
    });
    let html = fw
        .render(&config_str, input)
        .await
        .expect("render");
    assert!(html.starts_with("<!doctype html>"), "html head: {html}");
    assert!(html.contains("Hello from E2E"), "component rendered: {html}");
    assert!(html.contains("data-reactroot"), "react root marker: {html}");
    assert!(html.contains("<meta name=\"x-e2e\" content=\"yes\">"), "head merge: {html}");
    assert!(html.contains("<title>E2E"), "title emitted: {html}");
}

#[tokio::test]
#[ignore]
async fn end_to_end_missing_config_surfaces_clear_error() {
    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    let fw = FrameworkHost::new(pool);
    let bogus = format!(
        "/nonexistent/{}/oxide.config.mjs",
        unique_nonce()
    );
    let err = fw
        .load_config(&bogus)
        .await
        .expect_err("missing config must error");
    assert_eq!(err.0.code, "JSH-FRAMEWORK");
    let msg = &err.0.message;
    assert!(
        msg.contains("framework:load") || msg.contains("Cannot find") || msg.contains("ERR_MODULE_NOT_FOUND"),
        "message: {msg}"
    );
}
