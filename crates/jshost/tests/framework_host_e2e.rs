//! End-to-end test: real config file → real FrameworkAdapter → real SSR HTML
//! (spec §6.3, §7). Runtime proof that FrameworkHost works.
//!
//! Requires:
//!   - Node on PATH (>=22.18 for native TS stripping; the config imports the
//!     adapter's `.ts` modules from packages/react/src/)
//!   - pnpm-installed workspace node_modules (react, react-dom present)
//!
//! `#[ignore]` by default because it spawns a Node process and touches the
//! filesystem. Run explicitly:
//!     cargo test -p oxide-fw-jshost --test framework_host_e2e -- --ignored
//!
//! ## Test isolation
//!
//! Each test that writes a config uses a UNIQUE FILENAME at the base dir
//! `packages/react/.tmp-e2e/oxide-<nonce>.config.mjs`. The base dir is
//! deliberately inside `packages/react/` so the config's `from 'react'`
//! import resolves via the workspace node_modules, and its
//! `from '../src/real-adapter.ts'` relative import resolves to
//! `packages/react/src/real-adapter.ts`. Both paths are correct only when
//! the config file is a direct child of `.tmp-e2e/` — hence the unique
//! filename (not a unique subdir). Tests that only exercise missing-config
//! paths never write anything.

use oxide_fw_jshost::{CallStream, FrameworkHost, JsHost, NodeHost, PoolConfig};
use serde_json::json;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("crates/")
        .parent()
        .expect("workspace root")
        .to_path_buf()
}

fn e2e_base() -> PathBuf {
    workspace_root().join("packages/react/.tmp-e2e")
}

/// A monotonic counter combined with pid + nanos. Prevents the (real)
/// race where parallel tests call SystemTime::now() within the same
/// microsecond and produce an identical nonce — on macOS the clock has
/// ~1µs resolution, and two parallel `#[tokio::test]`s hitting it at the
/// same instant would then share a filename, one dropping the file the
/// other is about to import.
static NONCE_COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

fn unique_nonce() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let seq = NONCE_COUNTER.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
    format!("{pid}-{nanos}-{seq}", pid = std::process::id())
}

/// A unique config file path under `.tmp-e2e/`; removed on drop.
struct E2eConfigFile(PathBuf);

impl E2eConfigFile {
    fn new() -> Self {
        let dir = e2e_base();
        fs::create_dir_all(&dir).expect("mkdir .tmp-e2e");
        let name = format!("oxide-{}.config.mjs", unique_nonce());
        Self(dir.join(name))
    }
    fn path(&self) -> &Path {
        &self.0
    }
    fn path_str(&self) -> String {
        self.0.to_string_lossy().to_string()
    }
}

impl Drop for E2eConfigFile {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.0);
    }
}

const CONFIG_SOURCE: &str = r#"// Auto-generated by crates/jshost/tests/framework_host_e2e.rs
// Real React component + real react-dom/server dispatch through the
// FrameworkAdapter contract (spec §7). Removed by the test.

import { createRealAdapter } from '../src/real-adapter.ts'
import { createElement } from 'react'

const Home = (props) =>
  createElement('h1', { className: 'greeting' },
    'Hello from ' + String((props && props.data && props.data.name) || 'React'))

export default {
  framework: createRealAdapter({
    ssr: 'real',
    componentFor: (route) => (route === 'routes/index' ? Home : undefined),
  }),
}
"#;

#[tokio::test]
#[ignore]
async fn end_to_end_load_and_render_real_react_config() {
    let file = E2eConfigFile::new();
    fs::write(file.path(), CONFIG_SOURCE).expect("write config");
    let config_str = file.path_str();

    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    let fw = FrameworkHost::new(pool);

    // (1) load_config: descriptor round-trips through the real adapter.
    let descriptor = fw.load_config(&config_str).await.expect("load_config");
    assert_eq!(descriptor.name, "react", "adapter name from the config");
    assert_eq!(descriptor.extensions, vec![".tsx".to_string()]);
    assert_eq!(descriptor.capabilities["islands"], true);

    // (2) render: real react-dom/server HTML comes back through the host.
    let input = serde_json::json!({
        "route": "routes/index",
        "url": "/",
        "params": {},
        "data": { "name": "E2E" },
        "head": {
            "title": "E2E",
            "meta": [{ "name": "x-e2e", "content": "yes" }],
            "link": [], "style": [], "script": []
        },
    });
    let html = fw.render(&config_str, input).await.expect("render");
    assert!(html.starts_with("<!doctype html>"), "html head: {html}");
    assert!(
        html.contains("Hello from E2E"),
        "component rendered: {html}"
    );
    assert!(html.contains("data-reactroot"), "react root marker: {html}");
    assert!(
        html.contains("<meta name=\"x-e2e\" content=\"yes\">"),
        "head merge: {html}"
    );
    assert!(html.contains("<title>E2E"), "title emitted: {html}");
}

/// §6.4 / WP-B1–B3: with no `componentFor` in the config, the renderer must
/// consume `components.sources` (dev) and `components.entry` (prod) through
/// the worker's resolver. This is the end-to-end proof that route components
/// no longer live in `oxide.config.ts`.
#[tokio::test]
#[ignore]
async fn end_to_end_resolver_supplies_components_without_component_for() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/.tmp-e2e");
    fs::create_dir_all(&dir).expect("mkdir .tmp-e2e");
    let nonce = unique_nonce();
    let comp_a = dir.join(format!("comp-a-{nonce}.mjs"));
    let comp_b = dir.join(format!("comp-b-{nonce}.mjs"));
    let entry = dir.join(format!("entry-{nonce}.mjs"));
    fs::write(
        &comp_a,
        "import { createElement } from 'react'\nexport default () => createElement('h1', null, 'dev A')\n",
    )
    .unwrap();
    fs::write(
        &comp_b,
        "import { createElement } from 'react'\nexport const Page = () => createElement('h2', null, 'dev B')\n",
    )
    .unwrap();
    fs::write(
        &entry,
        format!(
            "import A from './comp-a-{nonce}.mjs'\nimport {{ Page as B }} from './comp-b-{nonce}.mjs'\nexport const routes = {{ 'routes/index': {{ default: A }}, 'routes/other': {{ Page: B }} }}\n"
        ),
    )
    .unwrap();

    struct Cleanup(Vec<PathBuf>);
    impl Drop for Cleanup {
        fn drop(&mut self) {
            for p in &self.0 {
                let _ = fs::remove_file(p);
            }
        }
    }
    let _cleanup = Cleanup(vec![comp_a.clone(), comp_b.clone(), entry.clone()]);

    let config_file = E2eConfigFile::new();
    fs::write(
        config_file.path(),
        "import { createRealAdapter } from '../src/real-adapter.ts'\n\
         export default { framework: createRealAdapter({ ssr: 'real' }) }\n",
    )
    .unwrap();
    let config_str = config_file.path_str();

    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    let fw = FrameworkHost::new(pool);

    let mut dev_input = serde_json::json!({
        "route": "routes/other",
        "url": "/other",
        "params": {}, "data": {}, "head": { "title": "x", "meta": [], "link": [], "style": [], "script": [] },
        "components": { "sources": {
            "routes/other": comp_b.to_string_lossy(),
        } },
    });
    let html = fw
        .render(&config_str, dev_input.clone())
        .await
        .expect("dev render");
    assert!(html.contains("dev B"), "dev sources resolved: {html}");

    dev_input["route"] = serde_json::json!("routes/other");
    dev_input["components"] = serde_json::json!({
        "entry": entry.to_string_lossy(),
    });
    let html = fw
        .render(&config_str, dev_input)
        .await
        .expect("prod entry render");
    assert!(
        html.contains("dev B"),
        "prod entry resolved (named export): {html}"
    );
}

#[tokio::test]
#[ignore]
async fn end_to_end_missing_config_surfaces_clear_error() {
    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    let fw = FrameworkHost::new(pool);
    let bogus = format!("/nonexistent/{}/oxide.config.mjs", unique_nonce());
    let err = fw
        .load_config(&bogus)
        .await
        .expect_err("missing config must error");
    assert_eq!(err.0.code, "JSH-FRAMEWORK");
    let msg = &err.0.message;
    assert!(
        msg.contains("framework:load")
            || msg.contains("Cannot find")
            || msg.contains("ERR_MODULE_NOT_FOUND"),
        "message: {msg}"
    );
}

#[tokio::test]
#[ignore]
async fn worker_preserves_adapter_chunk_boundaries() {
    // A custom framework adapter whose `render` returns a ReadableStream
    // with three distinct chunks. The worker must forward them as three
    // `call_chunk` frames — not concatenate and re-slice. This is what
    // makes the wire genuinely progressive: a React streaming renderer's
    // shell arrives before its boundaries.
    use std::fs;
    use std::path::PathBuf;

    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/.tmp-e2e");
    fs::create_dir_all(&dir).expect("mkdir .tmp-e2e");
    let config_path = dir.join(format!("chunk-e2e-{}.mjs", unique_nonce()));
    let config_src = r#"
export default {
  framework: {
    name: 'chunktest',
    extensions: ['.foo'],
    capabilities: {},
    render(_input) {
      return new ReadableStream({
        start(c) {
          c.enqueue(new TextEncoder().encode('AAA'));
          c.enqueue(new TextEncoder().encode('BBB'));
          c.enqueue(new TextEncoder().encode('CCC'));
          c.close();
        }
      });
    },
  },
}
"#;
    fs::write(&config_path, config_src).expect("write chunk test config");
    let config_str = config_path.to_string_lossy().to_string();

    struct Cleanup(PathBuf);
    impl Drop for Cleanup {
        fn drop(&mut self) {
            let _ = fs::remove_file(&self.0);
        }
    }
    let _cleanup = Cleanup(config_path.clone());

    // Path 1: streaming. Expect three chunks in the order the adapter
    // produced them.
    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn worker");
    let fw = FrameworkHost::new(pool);
    let mut s = fw
        .render_streaming(&config_str, json!({}))
        .await
        .expect("render_streaming");
    let mut chunks: Vec<Vec<u8>> = Vec::new();
    match &mut s {
        CallStream::Chunked(rx) => {
            while let Some(item) = rx.recv().await {
                chunks.push(item.expect("chunk").to_vec());
            }
        }
        CallStream::Complete(b) => chunks.push(b.to_vec()),
    }
    assert_eq!(
        chunks.len(),
        3,
        "three adapter chunks preserved on the wire; got {:?}",
        chunks
    );
    assert_eq!(chunks[0].as_slice(), b"AAA");
    assert_eq!(chunks[1].as_slice(), b"BBB");
    assert_eq!(chunks[2].as_slice(), b"CCC");

    // Path 2: collected. Concatenation must equal what `render` returns,
    // so a consumer that doesn't care about chunk boundaries sees the
    // same HTML either way.
    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn worker");
    let fw = FrameworkHost::new(pool);
    let collected = fw.render(&config_str, json!({})).await.expect("render");
    assert_eq!(collected, "AAABBBCCC");
}
