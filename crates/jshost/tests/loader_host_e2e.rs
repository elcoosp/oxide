//! End-to-end test: real `page.server.mjs` file → Node worker → `loader:run`
//! → typed output (spec §9.1). This is the runtime proof that the loader
//! phase works through the actual worker, matching `framework_host_e2e.rs`.
//!
//! Requires Node on PATH. `#[ignore]` by default because it spawns a Node
//! process. Run explicitly:
//!     cargo test -p oxide-jshost --test loader_host_e2e -- --ignored
//!
//! ## Test isolation
//!
//! Each test writes a UNIQUE `.mjs` file into `crates/jshost/tests/.tmp-e2e/`
//! and removes it on drop, so parallel execution can't collide. The files
//! are plain ESM with no bare imports, so Node resolves them from anywhere.
//! Test names describe the case: success, http-error, redirect, no-load,
//! missing-module.

use oxide_jshost::{LoaderHost, Pool, JsHost, NodeHost, PoolConfig};
use serde_json::json;
use std::fs;
use std::path::PathBuf;
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

fn e2e_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/.tmp-e2e")
}

/// A monotonic counter combined with pid + nanos. Prevents the (real)
/// race where parallel tests call SystemTime::now() within the same
/// microsecond and produce an identical nonce — on macOS the clock has
/// ~1µs resolution, and two parallel `#[tokio::test]`s hitting it at the
/// same instant would then share a filename, one dropping the file the
/// other is about to import.
static NONCE_COUNTER: std::sync::atomic::AtomicU64 =
    std::sync::atomic::AtomicU64::new(0);

fn unique_nonce() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let seq = NONCE_COUNTER.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
    format!("{pid}-{nanos}-{seq}", pid = std::process::id())
}

/// A unique `.mjs` file under `.tmp-e2e/`; removed on drop.
struct TempModule(PathBuf);

impl TempModule {
    fn write(source: &str) -> Self {
        let dir = e2e_dir();
        fs::create_dir_all(&dir).expect("mkdir .tmp-e2e");
        let path = dir.join(format!("loader-{}.mjs", unique_nonce()));
        fs::write(&path, source).expect("write loader module");
        Self(path)
    }
    fn path_str(&self) -> String {
        self.0.to_string_lossy().to_string()
    }
}

impl Drop for TempModule {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.0);
    }
}

fn make_host() -> LoaderHost {
    let host = NodeHost::new(NodeHost::worker_script_default());
    let pool: Arc<dyn Pool> = host
        .tooling_pool(PoolConfig::default())
        .expect("spawn node worker");
    LoaderHost::new(pool)
}

#[tokio::test]
#[ignore]
async fn loader_returns_data_through_worker() {
    let m = TempModule::write(
        r#"// auto-generated by loader_host_e2e.rs
export const load = async ({ route, params, url }) => ({
  title: 'Real Loader',
  route,
  slug: params?.slug ?? null,
  url,
});
"#,
    );

    let h = make_host();
    let out = h
        .run(
            &m.path_str(),
            json!({
                "route": "routes/blog/[slug]",
                "url": "/blog/hi",
                "params": { "slug": "hi" },
                "method": "GET",
                "headers": [],
            }),
        )
        .await
        .expect("loader ok");

    assert_eq!(out["status"], 200);
    assert_eq!(out["data"]["title"], "Real Loader");
    assert_eq!(out["data"]["route"], "routes/blog/[slug]");
    assert_eq!(out["data"]["slug"], "hi");
    assert_eq!(out["data"]["url"], "/blog/hi");
}

#[tokio::test]
#[ignore]
async fn loader_error_sentinel_becomes_ok_payload_not_worker_error() {
    // A load fn that throws an Error with `.status` (matching OxideHttpError
    // shape from packages/oxide/src/server/index.ts) is detected by the
    // worker and returned as `{ status: N, location: null }`, NOT as a
    // worker error. The pipeline maps `status` to the response code.
    let m = TempModule::write(
        r#"export const load = async () => {
  const err = new Error('not found');
  err.status = 404;
  throw err;
};
"#,
    );

    let h = make_host();
    let out = h
        .run(&m.path_str(), json!({ "route": "routes/x", "url": "/x" }))
        .await
        .expect("worker returned an ok payload for the error sentinel");
    assert_eq!(out["status"], 404);
    assert!(out["location"].is_null());
}

#[tokio::test]
#[ignore]
async fn loader_redirect_sentinel_carries_location() {
    let m = TempModule::write(
        r#"export const load = async () => {
  const err = new Error('redirecting');
  err.status = 303;
  err.location = '/login';
  throw err;
};
"#,
    );

    let h = make_host();
    let out = h
        .run(&m.path_str(), json!({ "route": "routes/x", "url": "/x" }))
        .await
        .expect("loader ok");
    assert_eq!(out["status"], 303);
    assert_eq!(out["location"], "/login");
}

#[tokio::test]
#[ignore]
async fn module_without_load_export_surfaces_jsh_loader() {
    let m = TempModule::write(r#"export const not_load = 1;"#);
    let h = make_host();
    let err = h
        .run(&m.path_str(), json!({}))
        .await
        .expect_err("no load export must error");
    assert_eq!(err.0.code, "JSH-LOADER");
    assert!(
        err.0.message.contains("no \\`load\\` export")
            || err.0.message.contains("no `load` export"),
        "message: {}",
        err.0.message
    );
}

#[tokio::test]
#[ignore]
async fn missing_module_surfaces_jsh_loader() {
    let h = make_host();
    let bogus = format!(
        "{}/definitely-missing-{}.mjs",
        e2e_dir().to_string_lossy(),
        unique_nonce()
    );
    let err = h
        .run(&bogus, json!({}))
        .await
        .expect_err("missing module must error");
    assert_eq!(err.0.code, "JSH-LOADER");
    let msg = &err.0.message;
    assert!(
        msg.contains("Cannot find")
            || msg.contains("ERR_MODULE_NOT_FOUND")
            || msg.contains("loader:run failed"),
        "message: {msg}"
    );
}
