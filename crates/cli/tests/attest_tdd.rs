//! TDD pins for the V2-F20 attested-reproducible-builds substrate
//! (`oxide_fw_cli::attest`, spec v0.2 §V2-F20).
//!
//! The whole surface is pure or seed-deterministic so the pins run without
//! a toolchain build behind them: the lockfile parsers take text, the
//! statement/SBOM builders take values, and the signing seam takes a
//! fixed-seed ed25519 key (`seed_to_pkcs8` + the PEM wrapper) so a
//! signature round trip is reproducible byte-for-byte.
//!
//! Written FIRST (red): these pins failed on unresolved-symbol errors
//! before the `attest` module existed. The only unpinned part is the
//! process glue in the command layer (`cmd_attest_build`'s git/env reads,
//! `cmd_verify --rebuild`'s temp-dir rebuild) — the same split the F18
//! `BuildProbe` seam used: the pure engine is pinned, the process shell is
//! wired and reviewed.
//!
//! Spec anchors (docs/spec-v0.2-draft.md §V2-F20):
//! - "sorted maps and file lists, path normalization (strip the project
//!   root), identical dist-digest for two builds in different directories"
//! - "no timestamps in artifacts (SOURCE_DATE_EPOCH for any needed time)"
//! - "tampering with one byte fails `verify`"
//! - "signature round trip", "SBOM contains known crates"

