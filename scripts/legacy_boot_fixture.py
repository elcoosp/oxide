#!/usr/bin/env python3
"""Mechanically simulate the CURRENT legacy generate_island_boot_entry
emission (crates/cli/src/boot_entry.rs at HEAD 491c129) to produce the
byte-exact fixture the M1 pins assert against. Two cases:
  A) root=/proj, react, {Counter: src/islands/counter.tsx}, loading={}, pwa=false
  B) root=/proj, react, {Counter, Price(vue->wait: mixed!) } -- no: keep single-fw;
     B) same but loading={routes/blog/[slug]/loading -> path}, pwa=true
Prints the two fixtures as Rust raw strings for the pin files.
"""

def fixture(root, framework, islands, loading, pwa):
    out = []
    out.append("// Generated by oxide-fw-cli -- island boot entry. Do not edit.\n")
    out.append("// Static imports resolve before any statement runs, so `boot()`\n")
    out.append("// can see both the adapter and the boot runtime's registration hook.\n")
    out.append(f"import {{ clientAdapter }} from '@oxide-fw/{framework}';\n")
    out.append("import { bootWithRouter, installBootRuntime } from '@oxide-fw/core/client/boot';\n")
    idents = []
    for name, src in islands.items():
        ident = "__island_" + "".join(c if (c.isalnum() and c.isascii()) or c == '_' else '_' for c in name)
        abs_path = root + "/" + src
        out.append(f'import {ident} from "{abs_path}";\n')
        idents.append((name, ident))
    out.append("\nconst modules = {\n")
    for name, ident in idents:
        out.append(f'  "{name}": {ident},\n')
    out.append("};\n\n")
    if loading:
        lids = []
        for route_id, src in loading.items():
            stripped = route_id
            if stripped.endswith("/loading"):
                stripped = stripped[: -len("/loading")]
            if stripped.startswith("routes"):
                stripped = stripped[len("routes"):]
            url_key = "/" if not stripped else stripped
            abs_path = root + "/" + src
            ident = "__loading_" + "".join(c if (c.isalnum() and c.isascii()) or c == '_' else '_' for c in route_id)
            out.append(f'import {ident} from "{abs_path}";\n')
            lids.append((url_key, ident))
        out.append("\nconst __loading_map = {\n")
        for url_key, ident in lids:
            out.append(f'  "{url_key}": {ident},\n')
        out.append("};\n\n")
    else:
        out.append("\nconst __loading_map = {};\n\n")
    out.append("installBootRuntime();\n")
    out.append(
        "window.__oxideRegisterAdapter(clientAdapter, async (chunk) => {\n"
        "  return modules[chunk] ?? (await import(chunk));\n});\n"
    )
    out.append(
        "fetch('/client/client.manifest.json')\n"
        "  .then((r) => (r.ok ? r.json() : undefined))\n"
        "  .then((manifest) => bootWithRouter(clientAdapter, { loading: __loading_map, manifest }))\n"
        "  .catch(() => bootWithRouter(clientAdapter, { loading: __loading_map }));\n"
    )
    out.append("import { reportWebVitals } from '@oxide-fw/core/client';\nreportWebVitals();\n")
    if pwa:
        out.append(
            "if (typeof navigator !== 'undefined' && 'serviceWorker' in navigator && !globalThis.__oxidePwaRegistered) {\n"
            "  globalThis.__oxidePwaRegistered = true;\n"
            "  var __oxidePwa = document.createElement('script');\n"
            "  __oxidePwa.src = '/pwa-register.js';\n"
            "  __oxidePwa.async = true;\n"
            "  document.head.appendChild(__oxidePwa);\n}\n"
        )
    return "".join(out)


A = fixture("/proj", "react", {"Counter": "src/islands/counter.tsx"}, {}, False)
B = fixture(
    "/proj",
    "react",
    {"Counter": "src/islands/counter.tsx"},
    {"routes/blog/[slug]/loading": "src/routes/blog/[slug]/loading.tsx"},
    True,
)

def rust_const(name, text):
    """Emit the fixture as a `concat!` of one literal per source line —
    no `\\` line continuations (they strip the next line's indentation)."""
    lines = text.split('\n')[:-1]  # the text ends with \n; last split is ''
    out = [f'const {name}: &str = concat!(']
    for ln in lines:
        esc = ln.replace('\\', '\\\\').replace('"', '\\"')
        out.append(f'    "{esc}\\n",')
    out.append(');')
    return '\n'.join(out)


for name, text in (("A", A), ("B", B)):
    print(f'===== FIXTURE {name} (repr) =====')
    print(repr(text))
    print()
print('===== RUST CONST A =====')
print(rust_const('LEGACY_BYTES_BARE', A))
print()
print('===== RUST CONST B =====')
print(rust_const('LEGACY_BYTES_FULL', B))
